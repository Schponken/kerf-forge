// Regenerate kerf/assets/viewer3d.js: node tools/viewer/build.mjs (needs `npm ci` in tools/render).
import { build } from '../render/node_modules/esbuild/lib/main.js';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync } from 'node:fs';
const here = dirname(fileURLToPath(import.meta.url));
const nm = join(here, '../render/node_modules');
const ver = JSON.parse(readFileSync(join(nm, 'three/package.json'), 'utf8')).version;
await build({
  entryPoints: [join(here, 'entry.js')], bundle: true, minify: true, format: 'iife', globalName: 'KV3',
  target: 'es2020', legalComments: 'none', nodePaths: [nm],
  alias: { 'three/addons': join(nm, 'three/examples/jsm') },
  banner: { js: `/* three.js r${ver} (MIT, https://github.com/mrdoob/three.js) subset for the Kerf viewer. Generated by tools/viewer/build.mjs */` },
  outfile: join(here, '../../kerf/assets/viewer3d.js'),
});
console.log('ok');
