"""Mac app: without Apple's command line tools the installed app is a launcher that keeps ONE window (a click while it
is open brings it forward, nothing new opens). The launcher is generated by tools/mac/install_app.sh; here it runs
against stubbed pgrep / curl / osascript / open, so the behaviour is proven without a Mac."""
import os
import stat
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _launcher(tmp_path):
    src = (ROOT / "tools/mac/install_app.sh").read_text()
    block = src[src.index('  cat > "$BUILD/KerfStudio" <<LAUNCH'):src.index("\nLAUNCH\n") + len("\nLAUNCH\n")]
    gen = tmp_path / "gen.sh"
    gen.write_text(block.replace("$BUILD/KerfStudio", str(tmp_path / "KerfStudio")))
    subprocess.run(["bash", str(gen)], env={**os.environ, "REPO": "/repo"}, check=True)
    return tmp_path / "KerfStudio"


def _stubs(tmp_path, running: bool, windows: int, server_up: bool):
    b = tmp_path / "bin"
    b.mkdir(exist_ok=True)
    log = tmp_path / "calls.log"
    stubs = {"pgrep": f"echo pgrep >> {log}; {'echo 4242' if running else 'exit 1'}",
             "curl": f"{'exit 0' if server_up else 'exit 7'}",
             "osascript": f'echo "osascript $*" >> {log}; case "$*" in *count*) echo {windows};; esac',
             "open": f'echo "open $*" >> {log}', "nohup": f'echo "nohup $*" >> {log}', "sleep": "exit 0", "seq": "echo 1"}
    for name, body in stubs.items():
        f = b / name
        f.write_text(f"#!/bin/bash\n{body}\n")
        f.chmod(f.stat().st_mode | stat.S_IEXEC)
    return b, log


def _run(tmp_path, **kw):
    app = _launcher(tmp_path)
    b, log = _stubs(tmp_path, **kw)
    home = tmp_path / "home"
    (home / "Applications" / "Google Chrome.app").mkdir(parents=True, exist_ok=True)
    env = {"PATH": f"{b}:/usr/bin:/bin", "HOME": str(home)}
    script = app.read_text().replace('export PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:$PATH"', "")
    app.write_text(script)
    subprocess.run(["bash", str(app)], env=env, check=True, timeout=30)
    return log.read_text() if log.exists() else ""


def test_open_window_is_brought_forward_not_duplicated(tmp_path):
    calls = _run(tmp_path, running=True, windows=1, server_up=True)
    assert "frontmost" in calls and "open -na" not in calls


def test_running_without_a_window_opens_exactly_one(tmp_path):
    calls = _run(tmp_path, running=True, windows=0, server_up=True)
    assert calls.count("open -na Google Chrome") == 1 and "nohup" not in calls


def test_cold_start_starts_the_engine_then_one_window(tmp_path):
    calls = _run(tmp_path, running=False, windows=0, server_up=False)
    assert "nohup /repo/tools/mac/start.sh" in calls and calls.count("open -na Google Chrome") == 1


