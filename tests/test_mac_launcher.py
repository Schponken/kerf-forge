def _git(*a, cwd):
    import subprocess
    return subprocess.run(["git", *a], cwd=cwd, capture_output=True, text=True, check=True).stdout


def test_update_keeps_local_changes_and_names_the_ones_that_block_it(tmp_path):
    import subprocess
    script = Path(__file__).resolve().parent.parent / "tools" / "mac" / "update_repo.sh"
    origin, work, other = tmp_path / "origin.git", tmp_path / "work", tmp_path / "other"
    _git("init", "-q", "--bare", "-b", "main", str(origin), cwd=tmp_path)
    for d in (work, other):
        _git("clone", "-q", str(origin), str(d), cwd=tmp_path)
        _git("config", "user.email", "t@t", cwd=d); _git("config", "user.name", "t", cwd=d)
    (other / "a.txt").write_text("a1\n"); (other / "b.txt").write_text("b1\n")
    _git("add", ".", cwd=other); _git("commit", "-qm", "one", cwd=other); _git("push", "-q", "origin", "main", cwd=other)
    _git("pull", "-q", "origin", "main", cwd=work); _git("branch", "-q", "-u", "origin/main", cwd=work)
    run = lambda: subprocess.run(["bash", str(script), str(work)], capture_output=True, text=True).stdout  # noqa: E731
    (other / "a.txt").write_text("a2\n"); _git("commit", "-qam", "two", cwd=other); _git("push", "-q", "origin", "main", cwd=other)
    (work / "b.txt").write_text("b-local\n")                       # a local edit the update doesn't touch
    out = run()
    assert out.startswith("UPDATED") and "kept" in out
    assert (work / "a.txt").read_text() == "a2\n" and (work / "b.txt").read_text() == "b-local\n"
    (other / "b.txt").write_text("b3\n"); _git("commit", "-qam", "three", cwd=other); _git("push", "-q", "origin", "main", cwd=other)
    out = run()                                                    # the same LINE changed on both sides: refuse, say why
    assert out.startswith("NOT-UPDATED") and "b.txt" in out and (work / "b.txt").read_text() == "b-local\n"
    assert run().startswith("NOT-UPDATED")
    _git("checkout", "--", "b.txt", cwd=work); _git("merge", "-q", "--ff-only", "origin/main", cwd=work)
    (other / "c.txt").write_text("1\n2\n3\n4\n5\n6\n"); _git("add", "c.txt", cwd=other); _git("commit", "-qm", "c", cwd=other)
    _git("push", "-q", "origin", "main", cwd=other); run()
    (other / "c.txt").write_text("1\n2\n3\n4\n5\nsix\n"); _git("commit", "-qam", "c2", cwd=other); _git("push", "-q", "origin", "main", cwd=other)
    (work / "c.txt").write_text("one\n2\n3\n4\n5\n6\n")         # same file, different lines: merges cleanly
    out = run()
    assert out.startswith("UPDATED") and (work / "c.txt").read_text() == "one\n2\n3\n4\n5\nsix\n", out


def test_dock_keeps_one_kerf_tile_and_every_other_item():
    import importlib.util
    spec = importlib.util.spec_from_file_location("dock", Path(__file__).resolve().parent.parent / "tools" / "mac" / "dock_dedupe.py")
    d = importlib.util.module_from_spec(spec); spec.loader.exec_module(d)
    tile = lambda url, label="": {"tile-data": {"file-data": {"_CFURLString": url}, "file-label": label}}  # noqa: E731
    dock = {"persistent-apps": [tile("file:///Applications/Safari.app/", "Safari"),
                                tile("file:///Users/s/Applications/Kerf%20Studio.app/", "Kerf Studio"),
                                tile("file:///Users/s/kerf-forge/Kerf%20Studio.app/", "Kerf Studio"),
                                tile("file:///Users/s/Applications/Kerf%20Studio.app/", "Kerf Studio"),
                                tile("file:///Applications/BambuStudio.app/", "BambuStudio")]}
    out, n = d.dedupe(dock, "/Users/s/Applications/Kerf Studio.app")
    labels = [t["tile-data"]["file-label"] for t in out["persistent-apps"]]
    assert n == 2 and labels == ["Safari", "Kerf Studio", "BambuStudio"]
    assert out["persistent-apps"][1]["tile-data"]["file-data"]["_CFURLString"].startswith("file:///Users/s/Applications/")
