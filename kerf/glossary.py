def name(check: str) -> str:
    """Plain name for a check (the check id itself if it isn't listed)."""
    return CHECKS.get(check, (check,))[0]


def as_json() -> dict:
    """What Studio loads: {checks: {id: {name, means}}, terms: {word: meaning}}."""
    return {"checks": {k: {"name": n, "means": m} for k, (n, m) in CHECKS.items()}, "terms": dict(TERMS)}
